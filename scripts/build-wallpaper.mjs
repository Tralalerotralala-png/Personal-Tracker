// Builds the wallpaper: bundles js/wallpaper/main.js and everything it imports into ONE
// classic script (wallpaper/wallpaper.js), because a web page opened from a folder (as
// Wallpaper Engine does) cannot reliably load ES modules. Also copies the stylesheet.
//
//   node scripts/build-wallpaper.mjs
//
// The bundler understands exactly the module syntax this project uses (named imports,
// export function / const / class, export { } from) and refuses anything else loudly,
// instead of guessing. No dependencies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
export const ENTRY = 'js/wallpaper/main.js';

const IMPORT_RE = /^import\s+([\s\S]*?)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm;
const EXPORT_DECL_RE = /^export\s+(async\s+function|function|const|let|class)\s+([A-Za-z_$][\w$]*)/gm;
const EXPORT_FROM_RE = /^export\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"];?[ \t]*$/gm;

function resolveSpec(fromId, spec) {
  if (!spec.startsWith('.')) throw new Error(`${fromId}: only relative imports can be bundled, found '${spec}'`);
  const id = path.posix.normalize(path.posix.join(path.posix.dirname(fromId), spec));
  if (!id.endsWith('.js')) throw new Error(`${fromId}: import '${spec}' must end in .js`);
  return id;
}

export function transformModule(id, source) {
  const refuse = (what) => { throw new Error(`${id}: ${what} is not supported by the wallpaper bundler`); };
  if (/^export\s+default\b/m.test(source)) refuse('"export default"');
  if (/^export\s*\*/m.test(source)) refuse('"export *"');
  if (/^export\s*\{[^}]*\}\s*;?[ \t]*$/m.test(source)) refuse('"export { }" without "from"');
  if (/\bimport\s*\(/.test(source)) refuse('dynamic import()');
  if (/\bimport\.meta\b/.test(source)) refuse('import.meta');
  if (/^import\s+['"]/m.test(source)) refuse('a side-effect-only import');

  const deps = [];
  let code = source.replace(IMPORT_RE, (_m, what, spec) => {
    const dep = resolveSpec(id, spec);
    deps.push(dep);
    const w = what.trim();
    if (w.startsWith('*')) {
      const m = w.match(/^\*\s+as\s+([\w$]+)$/);
      if (!m) refuse(`import form '${w}'`);
      return `const ${m[1]} = __require(${JSON.stringify(dep)});`;
    }
    if (!w.startsWith('{')) refuse('a default import');
    const names = w.slice(1, -1).split(',').map((n) => n.trim()).filter(Boolean).map((n) => n.replace(/\s+as\s+/, ': '));
    return `const { ${names.join(', ')} } = __require(${JSON.stringify(dep)});`;
  });

  code = code.replace(EXPORT_FROM_RE, (_m, list, spec) => {
    const dep = resolveSpec(id, spec);
    deps.push(dep);
    const assigns = list.split(',').map((n) => n.trim()).filter(Boolean).map((n) => {
      const [from, to] = n.split(/\s+as\s+/);
      return `__exports.${to ?? from} = __m.${from};`;
    });
    return `{ const __m = __require(${JSON.stringify(dep)}); ${assigns.join(' ')} }`;
  });

  const exported = [];
  code = code.replace(EXPORT_DECL_RE, (_m, kind, name) => { exported.push(name); return `${kind} ${name}`; });
  if (/^export\b/m.test(code)) refuse('this export form');

  return { code, deps, exported };
}

export function bundle({ root = ROOT, entry = ENTRY, read = (p) => fs.readFileSync(path.join(root, p), 'utf8') } = {}) {
  const modules = new Map();
  const queue = [entry];
  while (queue.length) {
    const id = queue.shift();
    if (modules.has(id)) continue;
    const t = transformModule(id, read(id));
    modules.set(id, t);
    queue.push(...t.deps);
  }

  const parts = [
    '/* Generated by scripts/build-wallpaper.mjs from the files under js/. Do not edit this file. */',
    '(function () {',
    '"use strict";',
    'const __defs = {};',
    'const __cache = {};',
    'function __define(id, fn) { __defs[id] = fn; }',
    'function __require(id) {',
    '  const cached = __cache[id];',
    '  if (cached) return cached.exports;',
    '  if (!__defs[id]) throw new Error("Missing module " + id);',
    '  const mod = (__cache[id] = { exports: {} });',
    '  __defs[id](__require, mod.exports);',
    '  return mod.exports;',
    '}',
  ];
  for (const [id, t] of [...modules].sort(([a], [b]) => a.localeCompare(b))) {
    parts.push(`__define(${JSON.stringify(id)}, function (__require, __exports) {`, '"use strict";', t.code.trimEnd());
    if (t.exported.length) parts.push(`Object.assign(__exports, { ${t.exported.join(', ')} });`);
    parts.push('});');
  }
  parts.push(`__require(${JSON.stringify(entry)});`, '})();', '');
  return { code: parts.join('\n'), modules: [...modules.keys()].sort() };
}

export function build({ root = ROOT } = {}) {
  const out = path.join(root, 'wallpaper');
  fs.mkdirSync(out, { recursive: true });
  const { code, modules } = bundle({ root });
  fs.writeFileSync(path.join(out, 'wallpaper.js'), code);
  fs.copyFileSync(path.join(root, 'css/app.css'), path.join(out, 'app.css'));
  return { bytes: code.length, modules };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const { bytes, modules } = build();
  console.log(`wallpaper/wallpaper.js: ${(bytes / 1024).toFixed(1)} KB from ${modules.length} modules`);
  console.log(modules.map((m) => `  ${m}`).join('\n'));
}
